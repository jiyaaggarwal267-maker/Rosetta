"""Embeds the fonts into src/fontcss.ts as base64 @font-face rules, so rendering never fetches a font over the network."""
import base64
from pathlib import Path

root = Path(__file__).resolve().parent.parent
faces = [
    ("Bricolage", "bricolage-grotesque-latin-{}-normal.woff2", ["300", "500", "700", "800"]),
    ("Geist", "geist-sans-latin-{}-normal.woff2", ["300", "400", "500", "600"]),
    ("GeistMono", "geist-mono-latin-{}-normal.woff2", ["300", "400", "500", "600"]),
]
rules = []
for family, pattern, weights in faces:
    for w in weights:
        data = base64.b64encode((root / "public/fonts" / pattern.format(w)).read_bytes()).decode()
        rules.append(f"@font-face{{font-family:'{family}';font-weight:{w};font-style:normal;font-display:block;src:url(data:font/woff2;base64,{data}) format('woff2');}}")
(root / "src/fontcss.ts").write_text("// Generated by scripts/embed_fonts.py. Fonts inline, no network.\nexport const FONT_CSS = " + repr("\n".join(rules)).replace("'", '"', 0) + ";\n")
print("src/fontcss.ts", sum(len(r) for r in rules) // 1024, "KB")
